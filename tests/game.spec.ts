import { expect, test, type Page } from '@playwright/test';

async function addGates(page: Page, gates: string[]) {
  for (const gate of gates) await page.getByRole('button', { name: `Add ${gate} gate`, exact: true }).click();
}

test('automatically applies additions and completes introductory puzzles, observing phase before interference', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'From zero to one' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Run circuit' })).toBeDisabled();
  await addGates(page, ['X']);
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await expect(page.locator('.bar-label strong')).toHaveText(['0%', '100%']);
  await expect(page.locator('.gate-slot.executed')).toHaveCount(1);

  await page.getByRole('button', { name: 'Next puzzle' }).click();
  await addGates(page, ['H']);
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await expect(page.locator('.bar-label strong')).toHaveText(['50%', '50%']);

  await page.getByRole('button', { name: 'Next puzzle' }).click();
  await addGates(page, ['H']);
  await expect(page.locator('.bar-label strong')).toHaveText(['50%', '50%']);
  await page.locator('.math-details summary').click();
  const currentAmplitudes = page.locator('.math-details code').filter({ hasText: /^Current:/ });
  const amplitudes = await currentAmplitudes.textContent();
  await addGates(page, ['Z']);
  await expect(page.locator('.bar-label strong')).toHaveText(['50%', '50%']);
  await expect(currentAmplitudes).not.toHaveText(amplitudes ?? '');
  await addGates(page, ['H']);
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await expect(page.locator('.bar-label strong')).toHaveText(['0%', '100%']);
  await expect(page.locator('footer')).toContainText('3 / 11 discoveries made');
  await expect(page.getByRole('button', { name: 'Step', exact: true })).toBeDisabled();
  expect(errors).toEqual([]);
});

test('supports preview, failure, reordering, removal, rewind, clear, and gate limits', async ({ page }) => {
  await page.goto('/');
  const addX = page.getByRole('button', { name: 'Add X gate', exact: true });
  await addX.focus();
  await expect(page.locator('.preview-note')).toContainText('X preview:');
  await expect(page.locator('.preview-value')).toHaveText(['After gate: 0%', 'After gate: 100%']);
  await addGates(page, ['X', 'X']);
  await expect(page.getByRole('status')).toContainText('Not quite the target.');
  await page.getByRole('button', { name: 'Remove gate 2', exact: true }).click();
  await expect(page.locator('.bar-label strong')).toHaveText(['100%', '0%']);
  await page.getByRole('button', { name: 'Run circuit' }).click();
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await page.getByRole('button', { name: 'Rewind', exact: true }).click();
  await expect(page.getByRole('status')).not.toContainText('Target reached.');
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Run circuit' })).toBeDisabled();
  await addGates(page, Array<string>(8).fill('X'));
  await expect(addX).toBeDisabled();
  await page.getByRole('button', { name: 'Remove gate 8', exact: true }).click();
  await expect(addX).toBeEnabled();

  await page.getByRole('button', { name: /The invisible difference/ }).click();
  await addGates(page, ['H', 'H', 'Z']);
  await page.getByRole('button', { name: 'Move gate 3 left', exact: true }).click();
  await expect(page.locator('.circuit-gates .gate-symbol')).toHaveText(['H', 'Z', 'H']);
  await page.getByRole('button', { name: 'Run circuit' }).click();
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await page.getByRole('button', { name: 'Move gate 2 right', exact: true }).click();
  await expect(page.locator('.circuit-gates .gate-symbol')).toHaveText(['H', 'H', 'Z']);
  await page.getByRole('button', { name: 'Run circuit' }).click();
  await expect(page.getByRole('status')).toContainText('Not quite the target.');
});

test('auto-applies keyboard additions after rewind or partial replay, with matching previews', async ({ page }) => {
  await page.goto('/');
  const addX = page.getByRole('button', { name: 'Add X gate', exact: true });
  await addX.focus();
  await addX.press('Enter');
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await page.getByRole('button', { name: 'Rewind', exact: true }).click();
  await expect(page.locator('.bar-label strong')).toHaveText(['100%', '0%']);
  await addX.focus();
  await expect(page.locator('.preview-value')).toHaveText(['After gate: 100%', 'After gate: 0%']);
  await addX.press('Enter');
  await expect(page.locator('.bar-label strong')).toHaveText(['100%', '0%']);
  await expect(page.locator('.gate-slot.executed')).toHaveCount(2);
  await expect(page.getByRole('status')).toContainText('Not quite the target.');

  await page.getByRole('button', { name: 'Rewind', exact: true }).click();
  await page.getByRole('button', { name: 'Step', exact: true }).click();
  await expect(page.locator('.bar-label strong')).toHaveText(['0%', '100%']);
  await expect(page.getByRole('status')).not.toContainText('Target reached.');
  await addX.focus();
  await expect(page.locator('.preview-value')).toHaveText(['After gate: 0%', 'After gate: 100%']);
  await addX.press('Enter');
  await expect(page.locator('.gate-slot.executed')).toHaveCount(3);
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await expect(page.locator('footer')).toContainText('1 / 11 discoveries made');

  await page.getByRole('button', { name: 'Rewind', exact: true }).click();
  await page.getByRole('button', { name: 'Run circuit' }).click();
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await page.getByRole('button', { name: 'Rewind', exact: true }).click();
  for (let index = 0; index < 3; index++) await page.getByRole('button', { name: 'Step', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Target reached.');
  await expect(page.locator('footer')).toContainText('1 / 11 discoveries made');
});

